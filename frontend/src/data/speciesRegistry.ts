export const getAllSpecies = (): SpeciesDetail[] => Object.values(SPECIES_REGISTRY);

export const getSpeciesByCategory = (category: SpeciesCategory): SpeciesDetail[] => {
  if (category === 'all') return getAllSpecies();
  return getAllSpecies().filter((sp) => sp.category === category);
};

export const getSpeciesById = (id: string): SpeciesDetail | undefined => SPECIES_REGISTRY[id];

export const parsePromptForSpecies = (prompt: string): {
  species?: SpeciesDetail;
  action?: AnimationAction;
  environment?: StageEnvironment;
} => {
  const p = prompt.toLowerCase();
  
  // 1. Match Species
  let matchedSpecies: SpeciesDetail | undefined;
  for (const sp of getAllSpecies()) {
    const nameLower = sp.name.toLowerCase();
    const idLower = sp.id.replace('_', ' ');
    if (p.includes(nameLower) || p.includes(idLower) || p.includes(nameLower.split(' ').pop() || '')) {
      matchedSpecies = sp;
      break;
    }
  }

  // 2. Match Action
  let matchedAction: AnimationAction | undefined;
  const actionKeywords: Record<string, AnimationAction> = {
    'running': 'run', 'run': 'run', 'sprint': 'run',
    'walking': 'walk', 'walk': 'walk', 'stalk': 'walk',
    'swimming': 'swim', 'swim': 'swim',
    'flying': 'fly', 'fly': 'fly', 'soar': 'fly',
    'glide': 'glide', 'gliding': 'glide',
    'slither': 'slither', 'slithering': 'slither',
    'crawl': 'crawl', 'crawling': 'crawl',
    'attack': 'attack', 'attacking': 'attack', 'roar': 'attack', 'bite': 'attack',
    'strike': 'strike', 'striking': 'strike',
    'jump': 'jump', 'jumping': 'jump', 'leap': 'jump',
    'eating': 'eat', 'eat': 'eat', 'feed': 'eat',
    'dive': 'dive', 'diving': 'dive',
    'perch': 'perch', 'perching': 'perch',
    'flap': 'wing_flap', 'flapping': 'wing_flap',
    'idle': 'idle', 'stand': 'idle', 'standing': 'idle',
  };

  for (const [kw, act] of Object.entries(actionKeywords)) {
    if (new RegExp(`\\b${kw}\\b`, 'i').test(p)) {
      matchedAction = act;
      break;
    }
  }

  // 3. Match Environment
  let matchedEnv: StageEnvironment | undefined;
  if (/ocean|underwater|sea|water|coral reef/i.test(p)) matchedEnv = 'ocean';
  else if (/jungle|rainforest|forest|woods|tropical/i.test(p)) matchedEnv = 'jungle';
  else if (/savannah|savanna|grassland|plains|desert/i.test(p)) matchedEnv = 'savannah';
  else if (/sky|clouds|air|altitude|flying high/i.test(p)) matchedEnv = 'sky';
  else if (/arctic|snow|ice|tundra|glacier/i.test(p)) matchedEnv = 'arctic';

  return {
    species: matchedSpecies,
    action: matchedAction || (matchedSpecies ? matchedSpecies.available_animations[0] : 'idle'),
    environment: matchedEnv || (matchedSpecies ? matchedSpecies.default_environment : 'studio'),
  };
};
